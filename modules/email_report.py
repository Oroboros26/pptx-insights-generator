"""
Email delivery: builds the HTML email body and sends via SendGrid or SMTP.
The email is a short teaser — exec summary bullets only. Full detail is in
the PDF and PPTX attachments.

Backend is selected by the EMAIL_PROVIDER env var:
  sendgrid  (default) — uses SENDGRID_API_KEY
  smtp      — uses SMTP_HOST, SMTP_PORT, SMTP_USER, SMTP_PASSWORD
"""
import os
import re as _re
from datetime import datetime, timedelta

from .utils import _abbrev_numbers, _parse_exec_summary


def _pdf_attach_name(pptx_filename):
    """Derive the PDF attachment name from the PPTX filename.
    Splits on either hyphen or whitespace to extract the week prefix (e.g. W20),
    so both 'W20-Retail_Weekly_Report.pptx' and 'W20 Retail Weekly Report.pptx'
    correctly produce 'W20 Retail Weekly Insight.pdf'."""
    prefix = _re.split(r"[-\s]", pptx_filename)[0]
    return f"{prefix} Retail Weekly Insight.pdf"


def _email_html(executive_summary, slide_results, pdf_attach_name, pptx_attach_name):
    """Build the HTML email body: title, greeting, exec summary bullets, sign-off.
    Full slide detail is in the attachments — the email body stays brief."""
    import html as _html_mod

    week_num   = datetime.now().isocalendar()[1]
    today      = datetime.now()
    monday     = today - timedelta(days=today.weekday())
    sunday     = monday + timedelta(days=6)
    date_range = f"{monday.strftime('%d')}&#8211;{sunday.strftime('%d %b %Y')}"
    run_date   = today.strftime("%d %b %Y")

    P = "#1a1a18"   # primary — near-black
    S = "#5f5e5a"   # secondary — body text
    M = "#888780"   # muted — captions

    sec = _parse_exec_summary(executive_summary) if executive_summary else {}

    # Build bullet list from exec summary highlights; fall back to splitting the overall paragraph
    _EMOJI = {"pos": "\U0001F4C8", "neg": "\U0001F4C9", "act": "\U0001F3AF"}  # 📈 📉 🎯
    points  = [(t, "pos") for t in sec.get("highlights_pos", [])]
    points += [(t, "neg") for t in sec.get("highlights_neg", [])]
    points += [(t, "act") for t in sec.get("priorities", [])]
    if not points:
        overall = (sec.get("overall") or executive_summary or "").strip()
        points  = [(s.strip(), "pos") for s in _re.split(r"(?<=[.!?])\s+", overall) if s.strip()]
    points = [(t, k) for t, k in points if t][:5]

    def _bullet_row(text, kind):
        e      = _html_mod.escape(_abbrev_numbers(text).strip())
        marker = _EMOJI.get(kind, "\U0001F4C8")
        return (f'<tr>'
                f'<td width="22" valign="top" style="font-size:14px;line-height:1.55;padding-right:4px;">{marker}</td>'
                f'<td style="font-size:14px;line-height:1.55;color:{S};padding-bottom:8px;">{e}</td>'
                f'</tr>')

    summary_rows = "".join(_bullet_row(t, k) for t, k in points) or (
        f'<tr><td style="font-size:14px;line-height:1.55;color:{S};">'
        f'No business summary available this week.</td></tr>')

    return f"""<!DOCTYPE html>
<html><head><meta charset="UTF-8"></head>
<body style="margin:0;padding:0;background:#ffffff;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif;">
<table cellpadding="0" cellspacing="0" border="0" width="100%" style="background:#ffffff;padding:24px 16px;">
<tr><td align="center">
<table cellpadding="0" cellspacing="0" border="0" width="560"
  style="background:#ffffff;padding:28px 28px 24px;">
<tr><td>

  <!-- TITLE -->
  <div style="font-size:19px;font-weight:700;letter-spacing:-0.01em;color:{P};">Weekly Performance Report</div>
  <div style="font-size:11px;color:{M};text-transform:uppercase;letter-spacing:0.06em;margin:6px 0 14px 0;padding-bottom:14px;border-bottom:2px solid {P};">
    W{week_num} &nbsp;&middot;&nbsp; {date_range}
  </div>

  <!-- GREETING -->
  <p style="font-size:14px;line-height:1.6;color:{S};margin:18px 0 0 0;">Hello,</p>
  <p style="font-size:14px;line-height:1.6;color:{S};margin:10px 0 0 0;">
    Here&#8217;s this week&#8217;s performance report. A short summary is below &#8212; the full report is attached as a PDF and PowerPoint.
  </p>

  <!-- EXECUTIVE SUMMARY BULLETS -->
  <p style="font-size:11px;font-weight:600;letter-spacing:0.10em;text-transform:uppercase;color:{M};margin:22px 0 10px 0;">Executive summary</p>
  <table cellpadding="0" cellspacing="0" border="0" width="100%" style="border-collapse:collapse;">
    {summary_rows}
  </table>

  <!-- SIGN-OFF -->
  <p style="font-size:14px;line-height:1.6;color:{S};margin:24px 0 0 0;">Best regards,</p>
  <p style="font-size:14px;font-weight:600;color:{P};margin:2px 0 0 0;">BI Team</p>

  <!-- FOOTER -->
  <p style="font-size:11px;color:{M};margin:22px 0 0 0;padding-top:14px;border-top:1px solid rgba(0,0,0,0.10);">
    Confidential &middot; Generated by AI &middot; {run_date}
  </p>

</td></tr>
</table>
</td></tr></table>
</body></html>"""


def send_email_sendgrid(pdf_path, pptx_path, subject, html_body, to_email):
    """Send the report via SendGrid. Attaches both the PDF and the PPTX."""
    import base64
    import sendgrid as sg_module
    from sendgrid.helpers.mail import (Mail, Attachment, FileContent,
                                       FileName, FileType, Disposition, ReplyTo)

    sg         = sg_module.SendGridAPIClient(api_key=os.environ["SENDGRID_API_KEY"])
    from_email = os.environ.get("REPORT_EMAIL_FROM", "noreply@example.com")
    reply_to   = os.environ.get("REPORT_EMAIL_REPLY_TO", "")

    message = Mail(from_email=from_email, to_emails=to_email,
                   subject=subject, html_content=html_body)
    if reply_to:
        message.reply_to = ReplyTo(reply_to)

    for path, name, mime in [
        (pdf_path,  _pdf_attach_name(os.path.basename(pptx_path)), "application/pdf"),
        (pptx_path, os.path.basename(pptx_path),
         "application/vnd.openxmlformats-officedocument.presentationml.presentation"),
    ]:
        with open(path, "rb") as f:
            message.add_attachment(Attachment(
                FileContent(base64.b64encode(f.read()).decode()),
                FileName(name), FileType(mime), Disposition("attachment"),
            ))

    response = sg.send(message)
    if response.status_code not in (200, 202):
        raise RuntimeError(f"SendGrid returned {response.status_code}: {response.body}")
    print(f"[Email] Sent via SendGrid to {to_email}")


def send_email_smtp(pdf_path, pptx_path, subject, html_body, to_email):
    """Send the report via SMTP (Office 365 by default). Used when EMAIL_PROVIDER=smtp."""
    import smtplib
    from email.mime.multipart import MIMEMultipart
    from email.mime.text import MIMEText
    from email.mime.base import MIMEBase
    from email import encoders

    smtp_host     = os.environ.get("SMTP_HOST", "smtp.office365.com")
    smtp_port     = int(os.environ.get("SMTP_PORT", "587"))
    smtp_user     = os.environ["SMTP_USER"]
    smtp_password = os.environ["SMTP_PASSWORD"]

    msg = MIMEMultipart("mixed")
    msg["Subject"] = subject
    msg["From"]    = smtp_user
    msg["To"]      = to_email
    msg.attach(MIMEText(html_body, "html"))

    for path, name, mime_type in [
        (pdf_path,  _pdf_attach_name(os.path.basename(pptx_path)), "application/pdf"),
        (pptx_path, os.path.basename(pptx_path),
         "application/vnd.openxmlformats-officedocument.presentationml.presentation"),
    ]:
        with open(path, "rb") as f:
            part = MIMEBase(*mime_type.split("/"))
            part.set_payload(f.read())
        encoders.encode_base64(part)
        part.add_header("Content-Disposition", "attachment", filename=name)
        msg.attach(part)

    with smtplib.SMTP(smtp_host, smtp_port) as server:
        server.starttls()
        server.login(smtp_user, smtp_password)
        server.sendmail(smtp_user, to_email, msg.as_string())
    print(f"[Email] Sent via SMTP to {to_email}")


def send_report_email(pdf_path, pptx_path, executive_summary, slide_results, filename):
    """Dispatch to the correct email backend based on EMAIL_PROVIDER env var.
    Skips silently if REPORT_EMAIL_TO is not set."""
    to_email = os.environ.get("REPORT_EMAIL_TO", "")
    if not to_email:
        print("[Email] REPORT_EMAIL_TO not set — skipping")
        return

    week_num  = datetime.now().isocalendar()[1]
    subject   = f"Weekly Performance Report (W{week_num})"
    pdf_name  = _pdf_attach_name(filename)
    html_body = _email_html(executive_summary, slide_results, pdf_name, filename)

    provider = os.environ.get("EMAIL_PROVIDER", "sendgrid").lower()
    if provider == "smtp":
        send_email_smtp(pdf_path, pptx_path, subject, html_body, to_email)
    else:
        send_email_sendgrid(pdf_path, pptx_path, subject, html_body, to_email)
